/** 業種名や入力語から大分類を求める（複数該当あり。例: 医療コンサルティング → コンサル・士業 + 医療） */
export function categorize(text: string): CategoryId[] {
  if (!text || text === 'その他') return [];
  return CATEGORIES.filter((c) => c.keywords.some((kw) => text.includes(kw))).map((c) => c.id);
}

