/** 段（from→to）に合う改善の型を返す */
export function playFor(from: Role, to: Role): Play {
  if (to === 'revenue') return PRICE;
  if (from === 'list') return to === 'activity' ? { ...VOLUME, metric: 'リスト消化率' } : CONTACT;
  switch (to) {
    case 'activity':
      return VOLUME;
    case 'contact':
      return CONTACT;
    case 'appointment':
      return APPOINTMENT;
    case 'meeting':
      return MEETING;
    case 'proposal':
      return PROPOSAL;
    case 'proposalVisit':
      return PROPOSAL_VISIT;
    case 'yomi':
      return YOMI;
    case 'yomiVisit':
      return YOMI_VISIT;
    case 'deal':
      return DEAL;
    default:
      return VOLUME;
  }
}

export const volumePlay = () => VOLUME;

/** 段の呼び名（例：架電数→アポ数 なら「アポ率」） */
export function stepLabel(from: Role, to: Role, toName: string): string {
  if (to === 'revenue') return '単価';
  if (to === 'activity') return from === 'list' ? 'リスト消化率' : `${toName}の比率`;
  if (to === 'meeting' && /^新規/.test(toName)) return '新規訪問率';
  if (to === 'deal' && from === 'yomiVisit') return 'ヨミ受注率';
  return playFor(from, to).metric.split('・')[0];
}
